/**
 * Lists the files the browser fetches to read the pictures of scanned pages (the tesseract.js
 * script and worker, the WebAssembly core, the Russian and English language data) as
 * `with { type: "file" }` imports, so `bun build --compile` embeds them in the executable.
 * Only the SIMD build of the LSTM core is taken: every browser from 2023 on has SIMD, and a
 * second build would add 4 MB for browsers that old. Re-run after upgrading the packages:
 *   bun run gen:ocr
 */
import { existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const modules = join(import.meta.dir, "../node_modules");
const picks: [string, string][] = [
  ["tesseract.min.js", "tesseract.js/dist/tesseract.min.js"],
  ["worker.min.js", "tesseract.js/dist/worker.min.js"],
  ["core/tesseract-core-simd-lstm.wasm.js", "tesseract.js-core/tesseract-core-simd-lstm.wasm.js"],
  ["lang/rus.traineddata.gz", "@tesseract.js-data/rus/4.0.0_best_int/rus.traineddata.gz"],
  ["lang/eng.traineddata.gz", "@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz"],
];

const lines: string[] = [];
const entries: string[] = [];
picks.forEach(([name, file], i) => {
  if (!existsSync(join(modules, file))) throw new Error(`missing ${file}: run bun install`);
  lines.push(`import f${i} from "../../node_modules/${file}" with { type: "file" };`);
  entries.push(`  ${JSON.stringify(name)}: f${i},`);
});

writeFileSync(
  join(import.meta.dir, "../src/server/ocrAssets.generated.ts"),
  `// @ts-nocheck — asset imports (.gz, .js from node_modules) have no type declarations\n// Generated by scripts/gen-ocr-assets.ts — do not edit.\n${lines.join("\n")}\n\n/** URL path under /ocr/ → file on disk (or embedded in the compiled executable). */\nexport const OCR_ASSETS: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`${picks.length} files`);
