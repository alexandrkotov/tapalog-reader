/**
 * Lists the two scripts the browser fetches to write a PDF (pdf-lib and its font reader, the ready-made UMD builds that
 * set the globals `PDFLib` and `fontkit`) as `with { type: "file" }` imports, so `bun build --compile` embeds them in the
 * executable. They are not part of the page's own script: the compiled program bundles that as one piece, and these two
 * would add 1.9 MB to what every visit downloads, while now only an export fetches them. Re-run after upgrading the packages:
 *   bun run gen:pdflib
 */
import { existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const modules = join(import.meta.dir, "../node_modules");
const picks: [string, string][] = [
  ["pdf-lib.min.js", "pdf-lib/dist/pdf-lib.min.js"],
  ["fontkit.umd.min.js", "@pdf-lib/fontkit/dist/fontkit.umd.min.js"],
];

const lines: string[] = [];
const entries: string[] = [];
picks.forEach(([name, file], i) => {
  if (!existsSync(join(modules, file))) throw new Error(`missing ${file}: run bun install`);
  lines.push(`import f${i} from "../../node_modules/${file}" with { type: "file" };`);
  entries.push(`  ${JSON.stringify(name)}: f${i},`);
});

writeFileSync(
  join(import.meta.dir, "../src/server/pdflibAssets.generated.ts"),
  `// @ts-nocheck — asset imports (.js from node_modules) have no type declarations\n// Generated by scripts/gen-pdflib-assets.ts — do not edit.\n${lines.join("\n")}\n\n/** URL path under /pdflib/ → file on disk (or embedded in the compiled executable). */\nexport const PDFLIB_ASSETS: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`${picks.length} files`);
