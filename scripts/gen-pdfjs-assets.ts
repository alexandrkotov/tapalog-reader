/**
 * Lists the pdf.js files the browser fetches at run time (the worker, the
 * JBIG2/JPEG 2000 decoders that scanned books need, fonts, CMaps, ICC
 * profiles) as `with { type: "file" }` imports, so `bun build --compile` embeds
 * them in the executable. Re-run after upgrading pdfjs-dist:
 *   bun run gen:pdfjs
 */
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const base = join(import.meta.dir, "../node_modules/pdfjs-dist");
const picks: { dir: string; keep: (name: string) => boolean }[] = [
  { dir: "build", keep: (n) => n === "pdf.worker.min.mjs" },
  { dir: "wasm", keep: (n) => n.endsWith(".wasm") && n !== "quickjs-eval.wasm" }, // quickjs only runs PDF form scripts
  { dir: "iccs", keep: (n) => n.endsWith(".icc") },
  { dir: "standard_fonts", keep: (n) => n.endsWith(".pfb") || n.endsWith(".ttf") },
  { dir: "cmaps", keep: (n) => n.endsWith(".bcmap") },
];

const lines: string[] = [];
const entries: string[] = [];
let i = 0;
for (const { dir, keep } of picks) {
  for (const name of readdirSync(join(base, dir)).filter(keep).sort()) {
    const id = `f${i++}`;
    lines.push(`import ${id} from "../../node_modules/pdfjs-dist/${dir}/${name}" with { type: "file" };`);
    entries.push(`  ${JSON.stringify(`${dir === "build" ? "" : `${dir}/`}${name}`)}: ${id},`);
  }
}

writeFileSync(
  join(import.meta.dir, "../src/server/pdfjsAssets.generated.ts"),
  `// @ts-nocheck — asset imports (.pfb, .bcmap, .icc, .mjs) have no type declarations\n// Generated by scripts/gen-pdfjs-assets.ts — do not edit.\n${lines.join("\n")}\n\n/** URL path under /pdfjs/ → file on disk (or embedded in the compiled executable). */\nexport const PDFJS_ASSETS: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`${i} files`);
