/**
 * Builds the visual editor for the text of a page: src/web/editor/bundle.ts with Milkdown and KaTeX in it becomes one script, and
 * the KaTeX style sheet and its fonts (only the woff2 ones, which every browser takes) are put beside it, all in assets/editor/.
 * They are not part of the page's own script: the compiled program bundles that as one piece, and the editor would add about
 * 0.7 MB to what every visit downloads, while now only the window for checking the text fetches it. The server holds the files
 * at /editor/ (listed in src/server/editorAssets.generated.ts as `with { type: "file" }` imports, so `bun build --compile`
 * embeds them). The built files are kept in the repository; run this again after upgrading Milkdown or KaTeX:
 *   bun run gen:editor
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { editorSourceHash } from "./editor-source";

const root = join(import.meta.dir, "..");
const out = join(root, "assets/editor");
const katex = join(root, "node_modules/katex/dist");
if (!existsSync(katex)) throw new Error("missing katex: run bun install");

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, "fonts"), { recursive: true });

const built = await Bun.build({ entrypoints: [join(root, "src/web/editor/bundle.ts")], target: "browser", format: "iife", minify: true });
if (!built.success) throw new Error(built.logs.map(String).join("\n"));
writeFileSync(join(out, "editor.js"), await built.outputs[0]!.text());

// every @font-face keeps its woff2 source only
const css = readFileSync(join(katex, "katex.min.css"), "utf8").replace(/src:url\((fonts\/[^)]+\.woff2)\) format\("woff2"\)(?:,url\([^)]+\) format\("[^"]+"\))*/g, 'src:url($1) format("woff2")');
if (/\.woff\)|\.ttf\)/.test(css)) throw new Error("a font source other than woff2 was left in the style sheet");
writeFileSync(join(out, "katex.css"), css);
const fonts = readdirSync(join(katex, "fonts")).filter((f) => f.endsWith(".woff2"));
for (const f of fonts) copyFileSync(join(katex, "fonts", f), join(out, "fonts", f));

writeFileSync(join(out, "source.sha256"), editorSourceHash() + "\n");

const names = ["editor.js", "katex.css", ...fonts.map((f) => `fonts/${f}`)];
writeFileSync(
  join(root, "src/server/editorAssets.generated.ts"),
  `// @ts-nocheck — asset imports (.js, .css and .woff2 files) have no type declarations\n// Generated by scripts/gen-editor-assets.ts — do not edit.\n${names.map((n, i) => `import f${i} from "../../assets/editor/${n}" with { type: "file" };`).join("\n")}\n\n/** URL path under /editor/ → file on disk (or embedded in the compiled executable). */\nexport const EDITOR_ASSETS: Record<string, string> = {\n${names.map((n, i) => `  ${JSON.stringify(n)}: f${i},`).join("\n")}\n};\n`,
);
console.log(`${names.length} files, editor.js ${(readFileSync(join(out, "editor.js")).length / 1024).toFixed(0)} KB`);
