import qrcode from "qrcode-generator";
import { t } from "./i18n";
import { api, badge, copyText, el, openModal } from "./ui";

export interface ShareTarget {
  id: string;
  name: string;
  ext: string;
  /** The current reader view, when the format has one worth sharing. */
  view: unknown;
}

interface Status {
  tunnelUrl: string | null;
  lanUrls: string[];
}

interface ShareRow {
  token: string;
  name: string | null;
  ext: string | null;
  expiresAt: number | null;
  createdAt: number;
}

export function qrSvg(text: string): string {
  const qr = qrcode(0, "M");
  qr.addData(text);
  qr.make();
  return qr.createSvgTag(4, 4);
}

/** Addresses a link can be opened at right now: the internet address if the tunnel is up, and this computer on the local network. */
function addressesFor(status: Status): { label: string; base: string }[] {
  const out: { label: string; base: string }[] = [];
  if (status.tunnelUrl) out.push({ label: t("share.internet"), base: status.tunnelUrl });
  const here = location.origin;
  const onTunnel = status.tunnelUrl !== null && here === status.tunnelUrl;
  if (!onTunnel) {
    // "localhost" means nothing to another device: use the computer's network address instead.
    const isLocalhost = /^(localhost|127\.|\[::1\])/.test(location.hostname);
    const lan = isLocalhost ? status.lanUrls[0] : here;
    out.push({ label: t("share.lan"), base: lan ?? here });
  }
  return out;
}

function linkCard(label: string, url: string): HTMLElement {
  const copy = el("button", { type: "button", class: "btn", textContent: t("common.copy") });
  copy.addEventListener("click", async () => {
    if (await copyText(url)) {
      copy.textContent = t("common.copied");
      setTimeout(() => (copy.textContent = t("common.copy")), 1500);
    }
  });
  const qr = el("div", { class: "qr", title: t("share.qr") });
  qr.innerHTML = qrSvg(url); // generated by the QR library from the URL: no user markup
  const input = el("input", { type: "text", readOnly: true, value: url });
  input.addEventListener("focus", () => input.select());
  return el("div", { class: "link-card" }, qr, el("div", { class: "link-info" }, el("strong", { textContent: label }), el("div", { class: "row" }, input, copy)));
}

export async function openShareDialog(target: ShareTarget): Promise<void> {
  const modal = openModal(t("share.title", { name: target.name }));
  const hasView = target.view !== null && target.view !== undefined;
  const exact = el("input", { type: "radio", name: "what", checked: true });
  const start = el("input", { type: "radio", name: "what", checked: !hasView });
  exact.checked = hasView;
  const expires = el("select");
  for (const [value, label] of [["", t("share.never")], ["1", t("share.days", { n: 1 })], ["7", t("share.days", { n: 7 })], ["30", t("share.days", { n: 30 })]] as const) {
    expires.append(el("option", { value, textContent: label }));
  }
  const results = el("div", { class: "link-results" });
  const create = el("button", { type: "button", class: "btn primary", textContent: t("share.create") });

  modal.body.append(
    el("div", { class: "reader-title" }, badge(target.ext), el("span", { textContent: target.name })),
    ...(hasView ? [el("label", { class: "choice" }, exact, t("share.exact")), el("label", { class: "choice" }, start, t("share.start"))] : []),
    el("label", { class: "field-row" }, el("span", { textContent: t("share.expires") }), expires),
    create,
    results,
    el("p", { class: "muted", textContent: t("share.note") }),
  );

  create.addEventListener("click", async () => {
    create.disabled = true;
    try {
      const made = await api<{ token: string }>("/api/shares", {
        bookId: target.id,
        view: hasView && exact.checked ? target.view : null,
        expiresInDays: expires.value ? Number(expires.value) : null,
      });
      const status = await api<Status>("/api/status");
      const addresses = addressesFor(status);
      results.replaceChildren(...addresses.map((a) => linkCard(a.label, `${a.base}/s/${made.token}`)));
      // a local-network link is a best effort: say so, and what to do instead
      if (addresses.some((a) => a.label === t("share.lan"))) results.append(el("p", { class: "muted", textContent: t("share.lanNote") }));
      if (!status.tunnelUrl) results.append(el("p", { class: "muted", textContent: t("share.needInternet") }));
    } finally {
      create.disabled = false;
    }
  });
}

export async function openMyLinks(): Promise<void> {
  const modal = openModal(t("share.mine"));
  const [{ shares }, status] = await Promise.all([api<{ shares: ShareRow[] }>("/api/shares"), api<Status>("/api/status")]);
  const base = addressesFor(status)[0]!.base;
  const render = (rows: ShareRow[]) => {
    if (!rows.length) return modal.body.replaceChildren(el("p", { class: "muted", textContent: t("share.none") }));
    modal.body.replaceChildren(
      ...rows.map((row) => {
        const url = `${base}/s/${row.token}`;
        const revoke = el("button", { type: "button", class: "btn", textContent: t("share.revoke") });
        revoke.addEventListener("click", async () => {
          await api(`/api/shares/${row.token}`, undefined, "DELETE");
          render(rows.filter((r) => r.token !== row.token));
        });
        const copy = el("button", { type: "button", class: "btn", textContent: t("common.copy") });
        copy.addEventListener("click", () => void copyText(url));
        const when = row.expiresAt ? t("share.expiresOn", { date: new Date(row.expiresAt).toLocaleDateString() }) : t("share.noLimit");
        return el("div", { class: "share-row" }, row.ext ? badge(row.ext) : el("span"), el("span", { class: "grow", textContent: row.name ?? "?" }), el("span", { class: "muted", textContent: when }), copy, revoke);
      }),
    );
  };
  render(shares);
}
